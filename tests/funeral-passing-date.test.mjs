import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { formsDatabase, id } from './helpers/formsDatabase.mjs';
import { funeralSchema } from './helpers/funeralForm.mjs';
import { validateAnswers } from '../supabase/functions/custom-forms/validation.mjs';
const read = path => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
test('date publication preserves historical versions, routing, closure and other questions', async t => {
  const { db, as, rpc } = await formsDatabase(); t.after(() => db.close());
  await db.exec(await read('supabase/migrations/20261023183820_form_question_guidance.sql'));
  const formId = await as(id(1), () => rpc('save_custom_form', [{ slug: 'funeral-enquiry', title: 'Arrange a funeral', description: 'Contact the office', schema: funeralSchema, enabled: true, task_title: 'Follow up', due_hours: 24, manager_ids: [id(1)], responsible_ids: [id(3)], watcher_ids: [] }]));
  await as(id(1), () => rpc('publish_custom_form', [formId]));
  const oldVersion = (await db.query('select * from custom_form_versions where form_id=$1', [formId])).rows;
  const routing = (await db.query('select * from custom_form_staff where form_id=$1 order by role', [formId])).rows;
  await db.query('update custom_forms set enabled=false where id=$1', [formId]);
  const migration = await read('supabase/migrations/20261025114022_funeral_passing_date.sql');
  await db.exec(migration);
  const after = (await db.query('select * from custom_forms where id=$1', [formId])).rows[0];
  assert.equal(after.enabled, false); assert.equal(after.published_version, 2);
  assert.deepEqual((await db.query('select * from custom_form_versions where form_id=$1 and version=1', [formId])).rows, oldVersion);
  assert.deepEqual((await db.query('select * from custom_form_staff where form_id=$1 order by role', [formId])).rows, routing);
  const fields = after.schema.fields, date = fields.find(f => f.id === 'when_passed');
  assert.equal(date.type, 'date'); assert.equal(date.required, false); assert.ok(!date.options);
  assert.deepEqual(fields.filter(f => f.id !== 'when_passed'), funeralSchema.fields.filter(f => f.id !== 'when_passed'));
  const answers = { request: 'Arranging a funeral', when_passed: '2026-10-24', current_location: 'Hospital', collection_needed: 'Yes', name: 'Visitor', phone: '0121 000 0000' };
  assert.doesNotThrow(() => validateAnswers(after.schema, answers));
  const { when_passed, ...unknown } = answers; assert.doesNotThrow(() => validateAnswers(after.schema, unknown));
  assert.throws(() => validateAnswers(after.schema, { ...answers, when_passed: '2026-02-30' }));
  await db.exec(migration);
  assert.equal((await db.query('select published_version from custom_forms where id=$1', [formId])).rows[0].published_version, 2);
  await db.query('update custom_forms set schema=$2 where id=$1', [formId, { fields: [...fields, { id: 'staff_note', type: 'text', label: 'New draft question' }] }]);
  await assert.rejects(() => db.exec(migration), /unpublished changes/); await db.exec('rollback');
});
